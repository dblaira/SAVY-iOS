def asset_json(obj):
    return json.dumps(obj, indent=2) + "\n"


def gen_assets(cfg):
    h = cfg["theme"].get("accentAsset", cfg["theme"]["accent"]).lstrip("#")
    comps = {c: f"{int(h[i:i + 2], 16) / 255:.3f}" for c, i in (("red", 0), ("green", 2), ("blue", 4))}
    accent = {"colors": [{"color": {"color-space": "srgb", "components": {
        "alpha": "1.000", "blue": comps["blue"], "green": comps["green"], "red": comps["red"]}},
        "idiom": "universal"}], "info": {"author": "xcode", "version": 1}}
    icon = {"images": [{"filename": "AppIcon.png", "idiom": "universal", "platform": "watchos",
                        "size": "1024x1024"}], "info": {"author": "xcode", "version": 1}}
    root = {"info": {"author": "xcode", "version": 1}}
    return {
        "Assets.xcassets/Contents.json": asset_json(root),
        "Assets.xcassets/AccentColor.colorset/Contents.json": asset_json(accent),
        "Assets.xcassets/AppIcon.appiconset/Contents.json": asset_json(icon),
    }


def gen_workflow(cfg):
    x = cfg["xcode"]
    text = template("ci/watch-build.yml", cfg).decode("utf-8")
    # A test class is named after its file unless xcode.testClasses says otherwise.
    classes = x.get("testClasses") or [Path(t).stem for t in x["testFiles"]]
    test_filter = " ".join(shlex.quote(f"-only-testing:{x['testTarget']}/{name}") for name in classes)
    # More folders whose changes start the build, beyond the kit's own (xcode.ciPaths).
    extra_paths = "".join(f'      - "{path}"\n' for path in x.get("ciPaths", []))
    text = text.replace("{{EXTRA_PATHS}}\n", extra_paths)
    values = {
        "PROJECT": x["project"], "APP_SCHEME": x["appScheme"], "WATCH_SCHEME": x["watchTarget"],
        # The same names as shell words: quoted only when they need it, such as a name with a space.
        "PROJECT_ARG": shlex.quote(x["project"]), "APP_SCHEME_ARG": shlex.quote(x["appScheme"]),
        "WATCH_SCHEME_ARG": shlex.quote(x["watchTarget"]),
        "WATCH_BUNDLE_ID": x["watchBundleID"], "TEST_FILTER": test_filter,
        "SHARED": x["sharedFolder"], "WATCH": x["watchTarget"], "WIDGETS": x["widgetTarget"],
        "TEST_DIR": x.get("testFolder", x.get("testTarget", "Tests")), "APP_NAME": cfg["appName"],
        # Match the Xcode the app is built with on Adam's Macs.
        "CI_RUNNER": x.get("ciRunner", "xcode-27"),
    }
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", value)
    if re.search(r"\{\{[A-Z_]+\}\}", text):
        sys.exit("Unfilled placeholder in templates/ci/watch-build.yml")
    return text


def planned_files(cfg, repo):
    """Every file `files` owns: destination path -> bytes."""
    p = places(cfg)
    files = {}
    for src, dst in copied(cfg):
        files[dst.format(**p)] = template(src, cfg)
    files[f"{p['shared']}/WatchCaptureConfig.swift"] = gen_config(cfg).encode()
    files[f"{p['watch']}/CaptureIntents.swift"] = gen_intents(cfg).encode()
    if route_of(cfg) == "icloud":
        # The only entitlement is iCloud's; an app on the iPhone route has none.
        files[f"{p['watch']}/{p['watch']}.entitlements"] = gen_entitlements(cfg).encode()
    files[f"{p['watch']}/Info.plist"] = gen_watch_info(cfg).encode()
    for rel, text in gen_assets(cfg).items():
        files[f"{p['watch']}/{rel}"] = text.encode()
    icon = repo / cfg["xcode"]["iosAppIcon"]
    if not icon.exists():
        sys.exit(f"xcode.iosAppIcon not found: {icon}")
    files[f"{p['watch']}/Assets.xcassets/AppIcon.appiconset/AppIcon.png"] = icon.read_bytes()
    files[".github/workflows/watch-build.yml"] = gen_workflow(cfg).encode()
    return files


def cmd_files(cfg, repo, check):
    differs = []
    for rel, data in planned_files(cfg, repo).items():
        path = repo / rel
        if check:
            if not path.exists() or path.read_bytes() != data:
                differs.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print("wrote", rel)
    dest = repo / cfg["xcode"]["sharedFolder"] / cfg["xcode"]["destinationFile"]
    if not dest.exists():
        print(f"still to write by hand: {dest.relative_to(repo)} (see SKILL.md, step 4)")
    if check:
        for rel in differs:
            print("differs from the kit:", rel)
        if differs:
            sys.exit(1)
        print("all kit files match")


def merge_back(template_text, route, app_text):
    """A template brought up to date with an app's copy of it, keeping the other route's lines.

    The app's copy is the template's lines for its route, changed. Each change is put back at
    the template line it came from. A new line next to a [route ...] block lands outside the
    block when it comes before it and inside when it comes at its end; look at those by hand.
    """
    lines = template_text.splitlines(keepends=True)
    kept = render_lines(template_text, route)
    old = [line for line, _ in kept]
    at = [index for _, index in kept]
    new = app_text.splitlines(keepends=True)
    out, position = [], 0
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(a=old, b=new, autojunk=False).get_opcodes():
        if tag == "equal":
            out += lines[position:at[i2 - 1] + 1]
            position = at[i2 - 1] + 1
        elif i2 > i1:
            # Changed or removed lines: the markers and the other route's lines between them stay.
            mine = set(at[i1:i2])
            out += lines[position:at[i1]] + new[j1:j2]
            out += [lines[k] for k in range(at[i1], at[i2 - 1] + 1) if k not in mine]
            position = at[i2 - 1] + 1
        else:
            out += new[j1:j2]
    merged = "".join(out + lines[position:])
    if render(merged, route) != app_text:
        sys.exit("the merged template would not give back the app's file; nothing was written")
    return merged


def cmd_sync(cfg, repo):
    p = places(cfg)
    for src, dst in copied(cfg):
        app_text = (repo / dst.format(**p)).read_bytes().decode("utf-8")
        before = (TEMPLATES / src).read_bytes().decode("utf-8")
        if render(before, route_of(cfg)) == app_text:
            print("template already matches", dst.format(**p))
            continue
        (TEMPLATES / src).write_bytes(merge_back(before, route_of(cfg), app_text).encode("utf-8"))
        print("template updated from", dst.format(**p))


