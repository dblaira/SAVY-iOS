#!/usr/bin/env python3
"""Watch capture kit: adds Apple Watch capture to one of Adam's iPhone/Mac apps.

First built for SAVY on Nov 20, 2026. One JSON config per app (see watch-capture.json at the
root of SAVY-iOS) drives everything:

  watchkit.py files  --config watch-capture.json [--repo .] [--check]
      Writes the shared Swift files, this app's WatchCaptureConfig.swift and CaptureIntents.swift,
      the Watch entitlements, asset catalog, complication Info.plist and the CI workflow.
      --check writes nothing and exits 1 if any file differs from what it would write.

  watchkit.py wire   --config watch-capture.json [--repo .]
      Adds the Watch app and complication targets, the shared files and the test files to
      the Xcode project, and writes a shared scheme for the Watch app. Refuses to run twice.

  watchkit.py embed  --config watch-capture.json [--repo .]
      Puts the Watch app inside the iPhone app (an "Embed Watch Content" step, for iOS only, so a
      Mac Catalyst build is unchanged). The Watch and iPhone apps only recognise each other as a
      pair when the iPhone app carries the Watch app; without it the live link fails with
      WatchConnectivity 7018. `wire` runs this too. Safe to run again.

  watchkit.py check  --config watch-capture.json [--repo .]
      Parses project.pbxproj and reports dangling references and what each target builds.

  watchkit.py xcodegen --config watch-capture.json [--repo .]
      For an app whose project is generated by XcodeGen (`"generator": "xcodegen"` in the config's
      xcode block): prints the targets, the embed line and the scheme to put in project.yml.
      `wire` and `embed` edit project.pbxproj, which the next `xcodegen generate` overwrites, so
      they refuse on such a project.

  watchkit.py sync   --config watch-capture.json [--repo .]
      Maintainer use, in SAVY-iOS only: copies SAVY's kit files back into templates/ after an
      improvement was made and verified in SAVY.

Two settings choose how an app differs from SAVY; without them everything is as in SAVY:

  "route": "icloud" (default) or "iphone"
      "iphone" is for an app that makes no iCloud calls. The Watch hands each capture to the iPhone
      over the Watch-to-iPhone link, the iPhone makes the entry, and the Watch keeps the capture
      until the iPhone says the entry is saved. No CloudKit, no iCloud entitlement.
  "xcode": {"generator": "pbxproj" (default) or "xcodegen"}

Templates hold both routes. A line `// [route icloud]` or `// [route iphone]` (`#` in YAML) starts
lines for that route only, and `// [route end]` ends them. `files` writes the lines for the app's
route and none of the marker lines.

Standard library only. No Xcode needed; Xcode or CI is still needed to compile the result.
"""
