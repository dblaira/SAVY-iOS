def load_config(path):
    cfg = json.loads(Path(path).read_text())
    if cfg.get("route", "icloud") not in ROUTES:
        sys.exit(f"route must be one of: {', '.join(ROUTES)}")
    if cfg.get("xcode", {}).get("generator", "pbxproj") not in GENERATORS:
        sys.exit(f"xcode.generator must be one of: {', '.join(GENERATORS)}")
    required = REQUIRED + (ICLOUD_REQUIRED if cfg.get("route", "icloud") == "icloud" else [])
    missing = [k for k in required if k not in cfg]
    missing += [f"kinds[{i}].{k}" for i, kind in enumerate(cfg.get("kinds", [])) for k in KIND_REQUIRED if k not in kind]
    missing += [f"xcode.{k}" for k in XCODE_REQUIRED if k not in cfg.get("xcode", {})]
    if missing:
        sys.exit(f"watch-capture config is missing: {', '.join(missing)}")
    for kind in cfg["kinds"]:
        if "{app}" not in kind["phrase"]:
            sys.exit(f"Siri phrase must contain {{app}}: {kind['phrase']}")
    if cfg["defaultKind"] not in [k["case"] for k in cfg["kinds"]]:
        sys.exit("defaultKind must be one of the kinds' cases")
    if "{app}" not in cfg["openPhrase"]:
        sys.exit("openPhrase must contain {app}")
    if not cfg["xcode"]["testFiles"]:
        sys.exit("xcode.testFiles must name the Watch capture test file(s) you will write (SKILL.md, step 7).")
    if len(cfg["kinds"]) + 1 > 10:
        sys.exit("An app can register at most 10 App Shortcuts; use fewer kinds.")
    return cfg


def places(cfg):
    x = cfg["xcode"]
    return {"shared": x["sharedFolder"], "watch": x["watchTarget"], "widgets": x["widgetTarget"]}


def route_of(cfg):
    return cfg.get("route", "icloud")


def copied(cfg):
    """Template file -> destination, for this app's route."""
    if route_of(cfg) == "icloud":
        return COPIED
    return [pair for pair in COPIED if pair[0] not in ICLOUD_ONLY] + IPHONE_ROUTE


def shared_for_app(cfg):
    """The shared files the iPhone (and Mac Catalyst) app builds, by name."""
    names = [Path(dst).name for src, dst in copied(cfg) if src.startswith("shared/")]
    return ["WatchCaptureConfig.swift"] + names + [cfg["xcode"]["destinationFile"]]


def shared_for_watch(cfg):
    """The shared files the Watch app builds too: its settings, the capture, and on the iPhone
    route the rules for handing a capture to the iPhone."""
    return ["WatchCaptureConfig.swift", "WatchCapture.swift"] + (
        ["WatchCaptureDelivery.swift"] if route_of(cfg) == "iphone" else [])


ROUTE_MARK = re.compile(r"[ \t]*(?://|#)[ \t]*\[route (\w+)\][ \t]*\r?\n?")


def render_lines(text, route):
    """The template's lines for one route: (line, its index in the template) pairs. Lines outside
    any `[route ...]` block belong to every route; the marker lines belong to none."""
    kept, active = [], None
    for index, line in enumerate(text.splitlines(keepends=True)):
        mark = ROUTE_MARK.fullmatch(line)
        if mark is None:
            if active in (None, route):
                kept.append((line, index))
        elif mark.group(1) == "end":
            active = None
        elif mark.group(1) in ROUTES:
            active = mark.group(1)
        else:
            sys.exit(f"unknown route in a template: {line.strip()}")
    if active is not None:
        sys.exit(f"a [route {active}] block in a template has no [route end]")
    return kept


def render(text, route):
    return "".join(line for line, _ in render_lines(text, route))


def template(src, cfg):
    """One template as this app gets it. Read as bytes so line endings stay as they are."""
    return render((TEMPLATES / src).read_bytes().decode("utf-8"), route_of(cfg)).encode("utf-8")


def swift(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def color(hex6):
    h = hex6.lstrip("#").upper()
    return f"Color(red: 0x{h[0:2]} / 255, green: 0x{h[2:4]} / 255, blue: 0x{h[4:6]} / 255)"


def strokes(lists):
    """Pen strokes for hand-drawn title lettering: a list of strokes, each a list of [x, y]."""
    if not lists:
        return "[]"
    rows = ["        [" + ", ".join(f"CGPoint(x: {x}, y: {y})" for x, y in stroke) + "]," for stroke in lists]
    return "[\n" + "\n".join(rows) + "\n    ]"


def kind_switch(cfg, name, doc, kind_type, value):
    lines = [f"    /// {doc}", f"    var {name}: {kind_type} {{", "        switch self {"]
    for kind in cfg["kinds"]:
        lines.append(f"        case .{kind['case']}: {value(kind)}")
    lines += ["        }", "    }"]
    return "\n".join(lines)


